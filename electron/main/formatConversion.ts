import { app, dialog, ipcMain } from 'electron'
import { spawn, type ChildProcess } from 'node:child_process'
import { randomUUID } from 'node:crypto'
import { access, copyFile, mkdir, mkdtemp, readFile, readdir, stat, writeFile } from 'node:fs/promises'
import { basename, dirname, isAbsolute, join } from 'node:path'
import { pathToFileURL } from 'node:url'
import sharp, { type Metadata, type FormatEnum } from 'sharp'
import { categoryOf, convertText, extensionOf, outputFileName, textExtensions, textTargets, type ConversionSource } from '../../src/shared/conversion'
import { getFFmpegPath } from './mediaTools'

const audioCodecs: Record<string, string> = { mp3: 'libmp3lame', wav: 'pcm_s16le', flac: 'flac', m4a: 'aac', aac: 'aac', ogg: 'libvorbis', opus: 'libopus', aiff: 'pcm_s16be', wma: 'wmav2' }
const videoCodecs: Record<string, string> = { mp4: 'libx264', mov: 'libx264', mkv: 'libx264', webm: 'libvpx-vp9', avi: 'mpeg4', mpeg: 'mpeg2video', ts: 'libx264' }
const imageCodecs: Record<string, string> = { bmp: 'bmp', ico: 'bmp' }
const writer = ['doc', 'docx', 'odt', 'rtf', 'txt', 'html']
const sheets = ['xls', 'xlsx', 'ods', 'csv', 'tsv']
const slides = ['ppt', 'pptx', 'odp']
const officeTargets = (extension: string) => (writer.includes(extension) ? [...writer, 'pdf'] : sheets.includes(extension) ? ['xlsx', 'xls', 'ods', 'csv', 'pdf'] : slides.includes(extension) ? [...slides, 'pdf'] : []).filter((id) => id !== extension)
const filters: Record<string, string> = { doc: 'doc:MS Word 97', docx: 'docx:Office Open XML Text', odt: 'odt:writer8', rtf: 'rtf:Rich Text Format', txt: 'txt:Text (encoded):UTF8', html: 'html:HTML (StarWriter)', xlsx: 'xlsx:Calc MS Excel 2007 XML', xls: 'xls:MS Excel 97', ods: 'ods:calc8', csv: 'csv:Text - txt - csv (StarCalc):44,34,76', pptx: 'pptx:Impress MS PowerPoint 2007 XML', ppt: 'ppt:MS PowerPoint 97', odp: 'odp:impress8', pdf: 'pdf' }

// Each renderer owns its source/result tokens; media stays on disk, never in app state or IPC buffers.
export function registerFormatConversion() {
  // Do not retain Windows file handles after a conversion (sources/results must remain removable).
  sharp.cache({ files: 0 })
  const sessions = new Map<number, { sources: Map<string, ConversionSource & { path: string; engine: 'sharp' | 'ffmpeg' | 'text' | 'office' | null }>; results: Map<string, { path: string; name: string; size: number }>; dirs: Set<string>; children: Set<ChildProcess>; busy: boolean; cancelled: boolean }>()
  let encoderCache: { path: string; encoders: Set<string> } | null = null
  const terminate = (child: ChildProcess) => {
    if (child.exitCode !== null || child.signalCode !== null) return
    if (process.platform !== 'win32' || !child.pid) { child.kill(); return }
    // LibreOffice launches a worker process; terminate that tree as well as the launcher.
    const killer = spawn('taskkill', ['/PID', String(child.pid), '/T', '/F'], { windowsHide: true, stdio: 'ignore', shell: false })
    killer.once('error', () => child.kill())
    killer.once('exit', (code) => { if (code) child.kill() })
  }
  const session = (event: Electron.IpcMainInvokeEvent) => {
    let value = sessions.get(event.sender.id)
    if (!value) {
      value = { sources: new Map(), results: new Map(), dirs: new Set(), children: new Set(), busy: false, cancelled: false }
      sessions.set(event.sender.id, value)
      const owned = value
      event.sender.once('destroyed', () => {
        owned.cancelled = true
        owned.children.forEach(terminate)
        void (async () => {
          // Conversions finish their own cleanup; wait for their finally blocks before removing profiles.
          while (owned.busy) await new Promise((resolve) => setTimeout(resolve, 50))
          await Promise.allSettled([...owned.dirs].map(cleanDirectory))
          sessions.delete(event.sender.id)
        })()
      })
    }
    return value
  }
  type Session = ReturnType<typeof session>
  async function cleanDirectory(path: string) {
    if (dirname(path) !== app.getPath('temp') || !basename(path).startsWith('sylunae-convert-')) return
    // All children are generated by us in this exact job directory (LibreOffice creates a profile tree).
    const { rm } = await import('node:fs/promises')
    await rm(path, { recursive: true, force: true, maxRetries: 3, retryDelay: 100 })
  }
  function run(owner: Session, executable: string, args: string[], allowFailure = false, timeout = 30 * 60_000): Promise<string> {
    return new Promise((resolve, reject) => {
      if (owner.cancelled) { reject(new Error('已取消转换')); return }
      const child = spawn(executable, args, { windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'], shell: false })
      owner.children.add(child)
      let output = ''; let expired = false
      const collect = (data: Buffer) => { output = (output + data.toString()).slice(-2_000_000) }
      child.stdout?.on('data', collect); child.stderr?.on('data', collect)
      const timer = setTimeout(() => { expired = true; terminate(child) }, timeout)
      child.once('error', (error) => { clearTimeout(timer); owner.children.delete(child); reject(error) })
      child.once('close', (code) => {
        clearTimeout(timer); owner.children.delete(child)
        if (owner.cancelled) reject(new Error('已取消转换'))
        else if (expired) reject(new Error('转换超时，请尝试较小的文件'))
        else if (code === 0 || allowFailure) resolve(output)
        else reject(new Error(`转换引擎无法处理此文件：${output.slice(-700)}`))
      })
    })
  }
  async function encoders(owner: Session) {
    const path = getFFmpegPath()
    if (!path) return new Set<string>()
    if (encoderCache?.path === path) return encoderCache.encoders
    const output = await run(owner, path, ['-hide_banner', '-encoders'], false, 15_000)
    const available = new Set([...output.matchAll(/^\s*[VAS][A-Z.]{5}\s+(\S+)/gm)].map((match) => match[1]))
    encoderCache = { path, encoders: available }
    return available
  }
  async function officePath() {
    const candidates = [
      ...['ProgramFiles', 'ProgramFiles(x86)', 'LOCALAPPDATA'].flatMap((key) => process.env[key] ? [join(process.env[key]!, 'LibreOffice', 'program', 'soffice.exe')] : []),
      ...(process.env.PATH ?? '').split(process.platform === 'win32' ? ';' : ':').filter(Boolean).map((path) => join(path, process.platform === 'win32' ? 'soffice.exe' : 'soffice')),
      '/Applications/LibreOffice.app/Contents/MacOS/soffice',
    ]
    for (const candidate of candidates) { try { await access(candidate); return candidate } catch { /* Try next installation. */ } }
    return null
  }
  function sharpTargets() {
    return ['jpg', 'png', 'webp', 'avif', 'gif', 'tiff'].filter((id) => sharp.format[(id === 'jpg' ? 'jpeg' : id === 'avif' ? 'heif' : id) as keyof FormatEnum]?.output.file)
  }
  ipcMain.handle('conversion:capabilities', async (event) => {
    const owner = session(event); owner.cancelled = false
    const available = await encoders(owner)
    return { ffmpeg: !!getFFmpegPath(), office: !!await officePath(), image: [...sharpTargets(), ...Object.keys(imageCodecs).filter((id) => available.has(imageCodecs[id]))] }
  })
  ipcMain.handle('conversion:inspect', async (event, path: unknown) => {
    const owner = session(event)
    if (owner.busy) throw new Error('请等待当前转换完成')
    owner.cancelled = false
    if (typeof path !== 'string' || !isAbsolute(path)) throw new Error('请选择本机文件')
    const info = await stat(path)
    if (!info.isFile() || !info.size) throw new Error('无法读取空文件或文件夹')
    const name = basename(path); const extension = extensionOf(name)
    const source: ConversionSource & { path: string; engine: 'sharp' | 'ffmpeg' | 'text' | 'office' | null } = { id: randomUUID(), name, size: info.size, category: categoryOf(name), detected: extension.toUpperCase(), targets: [], note: '', path, engine: null }
    // Detect image content, rather than trusting its filename.
    let metadata: Metadata | null = null
    try { metadata = await sharp(path, { limitInputPixels: 100_000_000 }).metadata() } catch { /* Fall back to media/document engines. */ }
    if (metadata) {
      source.category = 'image'; source.detected = (metadata.format ?? extension).toUpperCase(); source.engine = 'sharp'
      source.targets = sharpTargets()
      if ((metadata.pages ?? 1) > 1) source.note = '多帧或多页图片将转换第一帧；透明图片转 JPG/BMP 时使用白底。'
      else source.note = '保持原始尺寸；转 JPG/BMP 时透明区域使用白底，SVG 将栅格化。'
      const available = await encoders(owner)
      source.targets.push(...Object.keys(imageCodecs).filter((id) => available.has(imageCodecs[id])))
    } else if (source.category === 'audio' || source.category === 'video' || source.category === 'image') {
      const ffmpeg = getFFmpegPath()
      if (!ffmpeg) source.note = '需要下载媒体工具后重新识别此文件。'
      else {
        const probe = await run(owner, ffmpeg, ['-hide_banner', '-protocol_whitelist', 'file,pipe', '-i', path], true, 30_000)
        const hasVideo = probe.split('\n').some((line) => /Stream .*Video:/.test(line) && !line.includes('(attached pic)'))
        const hasAudio = /Stream .*Audio:/.test(probe)
        if (!hasVideo && !hasAudio) throw new Error('无法解码此文件，文件可能损坏或格式不受支持')
        source.engine = 'ffmpeg'
        if (source.category !== 'image') source.category = hasVideo ? 'video' : 'audio'
        source.detected = probe.match(/Input #0, (.*?), from/)?.[1]?.toUpperCase() || source.detected
        const available = await encoders(owner)
        source.targets = source.category === 'image' ? [...sharpTargets(), ...Object.keys(imageCodecs).filter((id) => available.has(imageCodecs[id]))] : [
          ...(hasVideo ? Object.keys(videoCodecs).filter((id) => available.has(videoCodecs[id]) && (!hasAudio || available.has(id === 'webm' ? 'libopus' : id === 'avi' ? 'libmp3lame' : id === 'mpeg' ? 'mp2' : 'aac'))) : []),
          ...(hasAudio ? Object.keys(audioCodecs).filter((id) => available.has(audioCodecs[id])) : []),
        ]
        source.note = source.category === 'image' ? '转换第一帧；转 JPG/BMP 时使用白底。' : hasAudio ? '视频可提取音轨；转换保留第一条视频/音频轨道，不包含字幕和附件。' : '未检测到音轨，仅提供视频输出；不包含字幕和附件。'
      }
    } else if (source.category === 'document') {
      if (textExtensions.includes(extension)) {
        if (info.size > 20 * 1024 * 1024) throw new Error('文本文档请控制在 20 MB 以内')
        source.engine = 'text'; source.targets = textTargets(extension)
        const text = new TextDecoder('utf-8', { fatal: true }).decode(await readFile(path))
        if (extension === 'json') {
          const data: unknown = JSON.parse(text.replace(/^\uFEFF/, ''))
          if (!Array.isArray(data) || !data.every((item) => Array.isArray(item)) && !data.every((item) => item !== null && typeof item === 'object' && !Array.isArray(item))) source.targets = source.targets.filter((id) => id !== 'csv' && id !== 'tsv')
        }
        source.note = '使用 UTF-8；CSV/TSV 转 JSON 输出二维数组；Markdown 转 HTML 保留原文，不渲染排版。'
      }
      if (extension === 'pdf') source.note = '暂不支持 PDF 反向转换或 OCR。'
      if (await officePath()) {
        source.targets.push(...officeTargets(extension))
        if (!source.engine && source.targets.length) source.engine = 'office'
        if (source.engine === 'office') source.note = '由本机 LibreOffice 转换；复杂排版、字体和公式可能存在差异。PDF 输入暂不支持反向转换。'
      } else if (!source.engine) source.note = extension === 'pdf' ? '暂不支持 PDF 反向转换或 OCR。' : '安装 LibreOffice 后点击重新识别，可转换 Office / OpenDocument 文档并导出 PDF。'
    } else source.note = '暂无法识别此类型，请选择图片、音视频或文档。'
    source.targets = [...new Set(source.targets)].filter((id) => id !== extension && !(extension === 'jpeg' && id === 'jpg') && !(extension === 'tif' && id === 'tiff'))
    owner.sources.set(source.id, source)
    const { path: _path, engine: _engine, ...publicSource } = source
    return publicSource
  })
  ipcMain.handle('conversion:convert', async (event, id: unknown, target: unknown, quality: unknown) => {
    const owner = session(event)
    const source = typeof id === 'string' ? owner.sources.get(id) : null
    if (owner.busy || !source || typeof target !== 'string' || !source.targets.includes(target) || typeof quality !== 'number' || !Number.isFinite(quality) || quality < 1 || quality > 100) throw new Error('无效的转换参数')
    owner.busy = true; owner.cancelled = false
    let directory: string
    try { directory = await mkdtemp(join(app.getPath('temp'), 'sylunae-convert-')) }
    catch (error) { owner.busy = false; throw error }
    owner.dirs.add(directory)
    const name = outputFileName(source.name, target); const output = join(directory, `output.${target}`)
    try {
      const extension = extensionOf(source.name)
      if (source.engine === 'text' && textTargets(extension).includes(target)) {
        await writeFile(output, convertText(new TextDecoder('utf-8', { fatal: true }).decode(await readFile(source.path)), extension, target), 'utf8')
      } else if (source.category === 'image') {
        let input = source.path
        const ffmpeg = getFFmpegPath()
        if (source.engine === 'ffmpeg') {
          if (!ffmpeg) throw new Error('请先下载媒体工具')
          input = join(directory, 'decoded.png')
          await run(owner, ffmpeg, ['-nostdin', '-hide_banner', '-loglevel', 'error', '-protocol_whitelist', 'file,pipe', '-i', source.path, '-frames:v', '1', input])
        }
        let pipeline = sharp(input, { limitInputPixels: 100_000_000 }).rotate()
        if (target === 'jpg' || target === 'bmp') pipeline = pipeline.flatten({ background: '#ffffff' })
        if (target === 'ico' || target === 'bmp') {
          if (!ffmpeg) throw new Error('请先下载媒体工具')
          const intermediate = join(directory, 'image.png')
          if (target === 'ico') pipeline = pipeline.resize(256, 256, { fit: 'inside', withoutEnlargement: true })
          await pipeline.png().toFile(intermediate)
          await run(owner, ffmpeg, ['-nostdin', '-hide_banner', '-loglevel', 'error', '-i', intermediate, '-frames:v', '1', '-c:v', 'bmp', output])
        } else {
          await pipeline.toFormat(target === 'jpg' ? 'jpeg' : target as keyof FormatEnum | 'avif', { quality, ...(target === 'png' ? { compressionLevel: 9 } : {}) }).toFile(output)
        }
      } else if (source.engine === 'ffmpeg') {
        const ffmpeg = getFFmpegPath()
        if (!ffmpeg) throw new Error('请先下载媒体工具')
        const audio = audioCodecs[target]
        const args = ['-nostdin', '-hide_banner', '-loglevel', 'error', '-protocol_whitelist', 'file,pipe', '-i', source.path]
        if (audio) {
          args.push('-map', '0:a:0', '-vn', '-c:a', audio)
          if (['mp3', 'aac', 'm4a', 'ogg', 'opus', 'wma'].includes(target)) args.push('-b:a', `${quality >= 90 ? 256 : quality >= 60 ? 192 : 96}k`)
          if (target === 'opus') args.push('-ar', '48000')
          if (target === 'mp3' || target === 'wma') args.push('-ac', '2')
        } else {
          args.push('-map', '0:v:0', '-map', '0:a:0?', '-c:v', videoCodecs[target], '-c:a', target === 'webm' ? 'libopus' : target === 'avi' ? 'libmp3lame' : target === 'mpeg' ? 'mp2' : 'aac')
          args.push('-vf', 'scale=trunc(iw/2)*2:trunc(ih/2)*2', '-pix_fmt', 'yuv420p')
          if (videoCodecs[target] === 'libx264' || target === 'webm') args.push('-crf', String(Math.round(40 - quality * .22)))
          if (target === 'webm') args.push('-b:v', '0')
          if (target === 'mp4' || target === 'mov') args.push('-movflags', '+faststart')
          if (target === 'mpeg') args.push('-r', '25')
        }
        args.push('-sn', '-dn', output)
        await run(owner, ffmpeg, args)
      } else {
        const office = await officePath()
        if (!office || !officeTargets(extension).includes(target)) throw new Error('此转换需要安装 LibreOffice')
        const incoming = join(directory, `input.${extension}`)
        await copyFile(source.path, incoming)
        const out = join(directory, 'converted'); await mkdir(out)
        await run(owner, office, [`-env:UserInstallation=${pathToFileURL(join(directory, 'profile')).href}`, '--headless', '--convert-to', filters[target], '--outdir', out, incoming], false, 120_000)
        const files = await readdir(out)
        const converted = files.find((file) => extensionOf(file) === target)
        if (!converted) throw new Error('LibreOffice 未能生成目标格式，请检查文件是否加密或损坏')
        // HTML export can include sidecar images; do not silently discard them.
        if (files.length > 1) throw new Error('该文档的 HTML 输出包含附属资源，请改用 PDF 或 DOCX 以保留完整内容')
        await copyFile(join(out, converted), output)
      }
      if (owner.cancelled) throw new Error('已取消转换')
      const info = await stat(output)
      if (!info.size) throw new Error('转换未生成有效文件')
      const resultId = randomUUID()
      owner.results.set(resultId, { path: output, name, size: info.size })
      return { id: resultId, name, size: info.size }
    } catch (error) {
      try { await cleanDirectory(directory); owner.dirs.delete(directory) } catch { /* Keep ownership for cleanup on renderer destruction. */ }
      throw error
    }
    finally { owner.busy = false }
  })
  ipcMain.handle('conversion:save', async (event, ids: unknown) => {
    const owner = session(event)
    if (!Array.isArray(ids) || !ids.length || ids.some((id) => typeof id !== 'string' || !owner.results.has(id))) throw new Error('无效的转换结果')
    const results = ids.map((id) => owner.results.get(id)!)
    if (results.length === 1) {
      const result = results[0]
      const chosen = await dialog.showSaveDialog({ title: '保存转换结果', defaultPath: join(app.getPath('downloads'), result.name), filters: [{ name: extensionOf(result.name).toUpperCase(), extensions: [extensionOf(result.name)] }] })
      if (chosen.canceled || !chosen.filePath) return 0
      await copyFile(result.path, chosen.filePath)
      return 1
    }
    const chosen = await dialog.showOpenDialog({ title: '保存全部转换结果', defaultPath: app.getPath('downloads'), properties: ['openDirectory', 'createDirectory'] })
    if (chosen.canceled || !chosen.filePaths[0]) return 0
    for (const result of results) {
      for (let index = 0; ; index++) {
        const name = index ? result.name.replace(/(\.[^.]+)$/, ` (${index})$1`) : result.name
        try { await copyFile(result.path, join(chosen.filePaths[0], name), 1); break }
        catch (error) { if ((error as NodeJS.ErrnoException).code !== 'EEXIST') throw error }
      }
    }
    return results.length
  })
  ipcMain.handle('conversion:cancel', (event) => { const owner = session(event); owner.cancelled = true; owner.children.forEach(terminate) })
  ipcMain.handle('conversion:release', async (event, ids: unknown) => {
    const owner = session(event)
    if (!Array.isArray(ids)) return
    // A component may unmount during conversion. Release after cancellation/Sharp completes.
    while (owner.busy) await new Promise((resolve) => setTimeout(resolve, 50))
    for (const id of ids) {
      if (typeof id !== 'string') continue
      owner.sources.delete(id)
      const result = owner.results.get(id)
      if (result) { const directory = dirname(result.path); await cleanDirectory(directory); owner.dirs.delete(directory); owner.results.delete(id) }
    }
  })
  return async () => {
    const owned = [...sessions.values()]
    for (const owner of owned) { owner.cancelled = true; owner.children.forEach(terminate) }
    while (owned.some((owner) => owner.busy)) await new Promise((resolve) => setTimeout(resolve, 50))
    await Promise.allSettled(owned.flatMap((owner) => [...owner.dirs].map(cleanDirectory)))
    sessions.clear()
  }
}
